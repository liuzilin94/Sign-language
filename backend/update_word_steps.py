def main():
    with app.app_context():
        updated = 0
        not_found = []

        for backend_id, steps in WORD_STEPS.items():
            word = Word.query.filter_by(backend_id=backend_id).first()
            if word:
                word.steps = json.dumps(steps, ensure_ascii=False)
                print(f"[OK] [{backend_id}] {word.word}: {steps[0]}")
                updated += 1
            else:
                not_found.append(backend_id)
                print(f"[--] [{backend_id}] NOT FOUND")

        db.session.commit()

        print(f"\n完成！共更新 {updated} 个词汇")
        if not_found:
            print(f"未找到 {len(not_found)} 个：{not_found}")


if __name__ == '__main__':
    main()
